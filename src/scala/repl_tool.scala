/*  Title:      src/scala/repl_tool.scala
    Author:     Qiyuan Xu

The `isabelle REPL` tool: start the Isa-REPL server on a logic session.  Runs in the JVM
that `isabelle` starts; models tat.scala (Theory-Agent-over-Trees).  Isa_REPL.Isa_REPL and
its ancestors outside the logic's heap are loaded through the PIDE document of the tool's
session (Isabelle_RPC's PIDE_Loader); the startup command lives in the tail of
library/Server.ML.

The service (Tools, REPL_Tool) names no Isabelle_RPC type: Isabelle constructs every tool
service at startup, so a missing or outdated Isabelle_RPC jar breaks only this tool
(REPL_Server), not every Isabelle/Scala tool.
*/

package isabelle.isa_repl

import isabelle._
import isabelle.isabelle_rpc.PIDE_Loader

import scala.collection.mutable


object REPL_Tool {
  val isabelle_tool: Isabelle_Tool =
    Isabelle_Tool("REPL", "start the Isa-REPL server on a logic session",
      Scala_Project.here, args => REPL_Server.run(args))
}

class Tools extends Isabelle_Scala_Tools(REPL_Tool.isabelle_tool)


object REPL_Server {

  /* the events the boot load, the ML side and the process report; the first ending wins */

  sealed abstract class Outcome
  case object Loaded extends Outcome
  case class Ready(addr: String) extends Outcome
  case class Failed(text: String) extends Outcome
  case class Ended(rc: Int, why: String) extends Outcome

  class Boot_Session(process_options: Options, background: Sessions.Background)
    extends PIDE_Loader.Session(process_options, background)

  def run(args: List[String]): Unit = {
    // 1a. first action: mark ourselves (and all we fork/exec) OOM-preferred
    try { File.write(Path.explode("/proc/self/oom_score_adj"), "1000") }
    catch { case _: Throwable => }

    val dirs = new mutable.ListBuffer[Path]
    var logic = Isabelle_System.default_logic()
    var qualifier: Option[String] = None
    val user_specs = new mutable.ListBuffer[Options.Spec]
    var wait_timeout = Time.seconds(600)
    var log_file: Option[Path] = None
    var mute = true

    val getopts = Getopts("""
Usage: isabelle REPL [OPTIONS] ADDR OUTPUT_DIR

  Options are:
    -l NAME      logic session (default: ISABELLE_LOGIC=""" + quote(logic) + """)
    -q NAME      default theory qualifier for client connections (default: LOGIC)
    -d DIR       as Isabelle's -d: a further session-root directory
    -o OPTION    as Isabelle's -o: override an Isabelle system option
    -T SECONDS   time to wait for load and for startup (default: 600)
    -L FILE      log the text of every prover message to FILE
    -V           do not mute the server's own output

  Start the Isa-REPL server: build the logic session's heap if needed, start
  an ML process with a Scala peer on it, load Isa_REPL, then serve on ADDR,
  storing files generated by evaluated theories under OUTPUT_DIR.
""",
      "L:" -> (arg => log_file = Some(Path.explode(arg))),
      "T:" -> (arg => wait_timeout = Time.seconds(Value.Double.parse(arg))),
      "V" -> (_ => mute = false),
      "d:" -> (arg => dirs += Path.explode(arg)),
      "l:" -> (arg => logic = arg),
      "o:" -> (arg => user_specs += Options.Spec.make(arg)),
      "q:" -> (arg => qualifier = Some(arg)))

    val (addr, output_dir) =
      getopts(args) match {
        case List(a, d) => (a, d)
        case _ => getopts.usage()
      }
    val qualifier_value = qualifier getOrElse logic
    // absolutise OUTPUT_DIR here, against the JVM's (the user's shell) cwd; the ML
    // process's cwd is a throwaway tmp dir, so a relative one must not reach it
    val output_dir_abs = Path.explode(output_dir).absolute.implode

    // the launch line, before building options, so a run is identifiable in the
    // log before any build
    Output.writeln(
      "Isa-REPL on " + quote(logic) + " at " + addr + ", output in " + quote(output_dir_abs),
      stdout = true)

    val dirs_list = dirs.toList
    val specs = user_specs.toList

    // two option sets, bound lexically apart: build_options lives only inside the block
    // that produces background/heaps, so the tool's content options cannot flow into the
    // shared logic heap, and passing process_options to Build.build_logic is a compile
    // error, not a review note.
    val (background, heaps) = {
      val build_options =
        Options.init(update = Options.Spec.ISABELLE_BUILD_OPTIONS) ++ specs
      val progress = new Console_Progress(stderr = true)
      progress.interrupt_handler {
        Build.build_logic(build_options, logic, dirs = dirs_list, progress = progress,
          build_heap = true, strict = true)
      }
      val bg = Sessions.background(build_options, logic, dirs = dirs_list).check_errors
      val hp = Store(build_options).session_heaps(bg, logic = logic)
      (bg, hp)
    }

    // defaults the user's -o may override; parallel_proofs=3 forks terminal proofs of loaded
    // theories as jEdit does
    val process_options =
      ((Options.init(update = Options.Spec.ISABELLE_BUILD_OPTIONS) + "quick_and_dirty=true" +
          "parallel_proofs=3") ++ specs) + "completion_limit=0" + "editor_tracing_messages=0" +
        "isabelle_rpc_dialogue=absent"

    val session = new Boot_Session(process_options, background)

    val loaded = Synchronized[Option[Outcome]](None)
    val ready = Synchronized[Option[Outcome]](None)
    val ending = Synchronized[Option[Outcome]](None)
    def fill(slot: Synchronized[Option[Outcome]], outcome: Outcome): Unit =
      slot.change(_ orElse Some(outcome))
    def fill_all(outcome: Ended): Unit =
      { fill(loaded, outcome); fill(ready, outcome); fill(ending, outcome) }
    def fill_startup(outcome: Outcome): Unit =
      { fill(loaded, outcome); fill(ready, outcome) }

    session.init_protocol_handler(new Session.Protocol_Handler {
      override val functions: Session.Protocol_Functions =
        List(
          "Isa_REPL.ready" -> ((_: Prover.Protocol_Output) =>
            { fill(ready, Ready(addr)); true }),
          "Isa_REPL.failed" -> ((msg: Prover.Protocol_Output) => {
            val text =
              Pretty.string_of(Symbol.decode_yxml_failsafe(msg.text),
                metric = Symbol.Metric, pure = true)
            Output.error_message(text)
            fill_startup(Failed(text))
            true
          }),
          "Isa_REPL.stopped" -> ((_: Prover.Protocol_Output) => {
            fill_all(Ended(Process_Result.RC.error,
              "Isa-REPL accept thread exited on " + addr))
            true
          }))
    })

    // the process ending before it answers is an ending too
    session.phase_changed +=
      Session.Consumer[Session.Phase]("Isa_REPL") {
        case Session.Terminated(result) =>
          fill_all(Ended(result.rc, "Isabelle process terminated: " + result.print_rc))
        case _ =>
      }

    // stderr: every syslog-class prover message, unconditionally
    session.syslog_messages +=
      Session.Consumer[Prover.Output]("Isa_REPL.syslog") { output =>
        Output.writeln(XML.content(output.message))
      }
    // -L FILE: the text of every prover message, one File.append each (no held writer);
    // the markup-only messages of loaded theories have no text and are skipped
    log_file.foreach { file =>
      session.all_messages +=
        Session.Consumer[Prover.Message]("Isa_REPL.log") {
          case output: Prover.Output =>
            val text = XML.content(output.message)
            if (text.nonEmpty) File.append(file, text + "\n")
          case _ =>
        }
    }

    val process =
      Isabelle_Process.start(process_options, session, background, heaps,
        eval_main = Command_Line.ML_tool(List("Isabelle_Process.init_build ()")),
        cwd = File.path(Isabelle_System.tmp_dir("isa_repl")),
        env = Isabelle_System.Settings.env(putenv = List(
          "REPL_DEFAULT_SESSION" -> qualifier_value,
          "REPL_PID" -> ProcessHandle.current().nn.pid().toString)))

    process.await_startup()

    def wait_for(slot: Synchronized[Option[Outcome]], what: String): Outcome = {
      val deadline = Time.now() + wait_timeout
      def loop(): Outcome =
        slot.timed_access(_ => Some(deadline), st => st.map(o => (o, st))) match {
          case Some(outcome) => outcome
          case None =>
            if (Time.now() < deadline) loop()
            else {
              // the timeout is discovered here, so it is reported here
              Output.error_message("Isa-REPL: timed out after " +
                wait_timeout.seconds.toLong + "s waiting for " + what)
              Failed("timed out waiting for " + what)
            }
        }
      loop()
    }

    def bail(outcome: Outcome): Nothing = {
      outcome match {
        case Failed(_) =>            // already written: the boot thread, the handler, or wait_for
        case Ended(_, why) => Output.error_message(why)
        case _ => Output.error_message("Isa-REPL startup failed")
      }
      session.stop()
      sys.exit(Process_Result.RC.error)
    }

    // 8. load Isa_REPL through the PIDE document, on an Isabelle thread (the loader's
    //    transitions are uninterruptible); every outcome fills the slot
    Isabelle_Thread.fork(name = "Isa_REPL.load") {
      Exn.capture { session.loader.use_theories(logic, "", List("Isa_REPL.Isa_REPL")) } match {
        case Exn.Res(_) => fill(loaded, Loaded)
        case Exn.Exn(exn) =>
          val text = Exn.message(exn)
          Output.error_message(text)
          fill_startup(Failed(text))
      }
    }
    wait_for(loaded, "load") match {
      case Loaded =>
      case other => bail(other)
    }

    // 9. start the server
    session.protocol_command("Isa_REPL.startup",
      XML.string(addr), XML.string(output_dir_abs), XML.string(if (mute) "true" else "false"))
    wait_for(ready, "startup") match {
      case Ready(_) =>
      case other => bail(other)
    }

    // 10. ready; then wait, without limit, for the first ending
    Output.writeln("Isa-REPL server ready at " + addr, stdout = true)
    ending.guarded_access(st => st.map(o => (o, st))) match {
      case Ended(rc, why) =>
        Output.error_message(why)
        session.stop()
        sys.exit(rc)
      case _ =>            // fill_startup never touches `ending`
        session.stop()
        sys.exit(Process_Result.RC.error)
    }
  }
}
